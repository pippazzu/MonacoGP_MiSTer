"""DC characterization of the D-2/7 VCO switch: TR16 (2SC458) driven from
IC40 pin 1 through R271 10K and D16 (MA150), R270 2.2K base to ground. Its
collector is held at 6 V (well out of saturation) while IC40.1 is swept
from 0 to 12 V; the collector current (A) goes to data/d2_tr16.json, which
d2_model.py reads, and limits it with R231 680 ohm and the saturated
transistor's 0.05 V. Needs ngspice.
Usage: characterize_d2_tr16.py [OUT.json]"""
import json
import sys
from pathlib import Path
import spice_run as S

HERE=Path(__file__).resolve().parent
DEFAULT_OUT=HERE/"data/d2_tr16.json"
GRID=(0.0,1/32,385)            # 0 .. 12 V

def main():
    net=""".title d2 tr16
.include parts.lib
VO o 0 0
R271 o n16 10k
D16 n16 b DMA150
R270 b 0 2.2k
Q16 c b 0 Q2SC458
VC c 0 6
"""
    x0,dx,n=GRID
    x,d=S.run(net,f"dc VO {x0} {x0+dx*(n-1)} {dx}",["i(VC)"])
    if len(x)!=n: raise RuntimeError(f"expected {n} points, got {len(x)}")
    out={"grid":list(GRID),"i":[round(-i,12) for i in d["i(VC)"]],
         "note":"TR16 collector current (parts.lib Q2SC458, collector at 6 V) against "
                "IC40 pin 1, through R271 10K and D16 MA150 with R270 2.2K base to "
                "ground. Generated by characterize_d2_tr16.py."}
    dst=Path(sys.argv[1]) if len(sys.argv)>1 else DEFAULT_OUT
    dst.write_text(json.dumps(out,indent=0)+"\n")

if __name__=="__main__": main()
