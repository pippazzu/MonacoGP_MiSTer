"""DC characterization of the D-7/7 ramp reset: TR12 (or TR13), a 2SC458
driven from a 74123 output at its high level (3.4 V, as the XSPICE one-shot
in spice/d67_cars.cir) through R228 10K with 10K base to ground, pulling the
integrator's - input through R173 100 ohm. Sweeps that input from -0.5 to
12.5 V and writes the current it sinks (A) to data/d7_reset_tr.json, which
d67_model.py reads (one table serves both ramps). Needs ngspice.
Usage: characterize_d7_reset.py [OUT.json]"""
import json
import sys
from pathlib import Path
import spice_run as S

HERE=Path(__file__).resolve().parent
DEFAULT_OUT=HERE/"data/d7_reset_tr.json"
GRID=(-0.5,1/16,209)           # -0.5 .. 12.5 V

def main():
    net=""".title d7 reset transistor
.include parts.lib
VQ q 0 3.4
R228 q b 10k
R12b b 0 10k
Q12 c b 0 Q2SC458
R173 vm c 100
VM vm 0 0
"""
    x0,dx,n=GRID
    x,d=S.run(net,f"dc VM {x0} {x0+dx*(n-1)} {dx}",["i(VM)"])
    if len(x)!=n: raise RuntimeError(f"expected {n} points, got {len(x)}")
    out={"grid":list(GRID),"i":[round(-i,12) for i in d["i(VM)"]],
         "note":"current sunk by R173 + TR12 (parts.lib Q2SC458, base from 3.4 V "
                "through 10K, 10K to ground) against the voltage at R173's free end. "
                "Generated by characterize_d7_reset.py."}
    dst=Path(sys.argv[1]) if len(sys.argv)>1 else DEFAULT_OUT
    dst.write_text(json.dumps(out,indent=0)+"\n")

if __name__=="__main__": main()
