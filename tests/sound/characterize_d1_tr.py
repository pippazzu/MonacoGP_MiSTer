"""DC characterization of the D-1/7 band-pass shunt: R349 100 ohm and the
2SC458 (TR) from node A to ground, the base driven from IC53 pin 14
(the C63 follower) through R308 10K with R343 10K to ground.

For each follower level on GRID (0 .. 6 V) node A is swept over
-VA_LIM .. +VA_LIM (the filter's node A stays within about +-25 mV once the
transistor conducts) and the current into R349 is fitted with a cubic in
the node-A voltage. The four coefficients per level go to data/d1_tr.json,
which d1_model.py reads (and interpolates between levels); the fit's worst
error is stored with them. Needs ngspice.
Usage: characterize_d1_tr.py [OUT.json]"""
import json
import sys
from pathlib import Path
import numpy as np
import spice_run as S

HERE=Path(__file__).resolve().parent
DEFAULT_OUT=HERE/"data/d1_tr.json"
GRID=(0.0,1/32,193)            # follower output, 0 .. 6 V
VA_LIM=0.04
VA_STEP=0.0025

def main():
    net=""".title d1 tr
.include parts.lib
VA na 0 0
R349 na tc 100
Q1 tc tb 0 Q2SC458
VF f 0 0
R308 f tb 10k
R343 tb 0 10k
"""
    x0,dx,n=GRID
    na=int(round(2*VA_LIM/VA_STEP))+1
    va=np.linspace(-VA_LIM,VA_LIM,na)
    coef=[[],[],[],[]]; worst=0.0
    for k in range(n):
        vf=x0+dx*k
        x,d=S.run(net.replace("VF f 0 0",f"VF f 0 {vf!r}"),
                  f"dc VA {-VA_LIM} {VA_LIM} {VA_STEP}",["i(VA)"])
        if len(x)!=na: raise RuntimeError(f"expected {na} points, got {len(x)}")
        i=-np.array(d["i(VA)"])             # into R349 from node A
        p=np.polyfit(np.array(x),i,3)
        err=np.abs(np.polyval(p,np.array(x))-i).max()
        worst=max(worst,err)
        for j in range(4): coef[j].append(float(p[3-j]))
    out={"grid":list(GRID),"va_lim":VA_LIM,"c0":coef[0],"c1":coef[1],"c2":coef[2],"c3":coef[3],
         "fit_err_a":worst,
         "note":"Current (A) from node A into R349 100R and the 2SC458 (parts.lib Q2SC458), "
                "base from the follower level through R308 10K, R343 10K to ground: "
                "c0 + c1*va + c2*va^2 + c3*va^3 for |va| <= va_lim, per follower level "
                "on grid. Generated by characterize_d1_tr.py."}
    dst=Path(sys.argv[1]) if len(sys.argv)>1 else DEFAULT_OUT
    dst.write_text(json.dumps(out,indent=0)+"\n")
    print(f"{n} levels, worst cubic fit error {worst*1e9:.1f} nA")

if __name__=="__main__": main()
