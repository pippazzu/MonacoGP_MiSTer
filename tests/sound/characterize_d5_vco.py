"""Characterization of the D-5/7 sawtooth oscillators (IC2 integrator, IC4
Schmitt, TR2 reset through R22 560 ohm; IC3/IC5/TR3 are the same parts)
against their control voltage, in the pin-wired parts of
spice/d5_hiscore.cir with the control voltage (IC1 pin 8 or 14) held by an
ideal source.

The sawtooth falls at a constant rate while the Schmitt is low and rises
at a nearly constant rate while TR2 resets the capacitor. Its switching
points lie beyond the Schmitt thresholds by the comparator's delay (TL081
small-signal response and slew), TR2's turn-off and the integrator's own
settling, all well under one model step. For each control voltage this
script fits a line to the interior of every falling and every rising
segment and takes their intersections as the effective turning points, so
a two-slope model with these corners has the reference's period. Written
to data/d5_vco.json for d5_model.py:
  cv            the control-voltage grid
  top, bot      the effective turning points (V)
  r_dn, r_up    the falling and rising slopes (V/s, both positive)
  period        the reference's mean period (s), as a check
R29 (overwritten on the drawing) sets the + input; the script takes it as
an argument with the same default as d5_model.py.
Needs ngspice. Usage: characterize_d5_vco.py [R29_OHM [OUT.json]]"""
import json
import sys
from pathlib import Path
import numpy as np
import spice_run as S

HERE=Path(__file__).resolve().parent
DEFAULT_OUT=HERE/"data/d5_vco.json"
CV_GRID=(0.25,0.125,31)        # 0.25 .. 4.0 V
TMAX="0.1u"                    # 1 us steps put the period 1.8 % off at 1 V
CYCLES=8

NET=""".title d5 vco
.include opamps.lib
.include parts.lib
V12 v12 0 12
V6 v6 0 6
Vcv cv 0 {cv}
R26 cv i2m 51k
R27 cv i2p 51k
R29 i2p 0 {r29}
C4 i2m saw 0.022u
XIC2 i2p i2m saw v12 0 TL081
R25 o4 i4p 100k
R32 i4p v6 47k
XIC4 i4p saw o4 v12 0 TL081
R24 o4 n24 10k
D2 n24 b2 DMA150
R30 b2 0 2.2k
Q2 c2 b2 0 Q2SC458
R22 i2m c2 560
.ic v(saw)=7.0 v(o4)=1.5
"""

def fit(x,y):
    a,b=np.polyfit(x,y,1)
    return a,b

def characterize(cv,r29):
    f_est=150.0*cv
    t_end=0.004+CYCLES/f_est
    x,d=S.run(NET.format(cv=cv,r29=r29),f"tran {TMAX} {t_end} 0 {TMAX} uic",
              ["v(saw)","v(o4)"],save_only=True)
    x=np.array(x); s=np.array(d["v(saw)"]); hi=np.array(d["v(o4)"])>6.0
    edges=np.flatnonzero(hi[1:]!=hi[:-1])+1
    segs=[(edges[k],edges[k+1],hi[edges[k]]) for k in range(len(edges)-1)]
    segs=[g for g in segs if x[g[0]]>0.002]          # skip the start-up
    lines=[]
    for a,b,h in segs:
        n=b-a; lo,up=a+max(n//10,2),b-max(n//10,2)
        if up-lo<5: continue
        k,c=fit(x[lo:up],s[lo:up])
        lines.append((h,k,c,x[a],x[b]))
    tops,bots,dn,upr=[],[],[],[]
    for (h1,k1,c1,_,_),(h2,k2,c2,_,_) in zip(lines,lines[1:]):
        if h1==h2: continue
        t=(c2-c1)/(k1-k2); v=k1*t+c1
        (tops if h1 else bots).append(v)
    for h,k,_,_,_ in lines: (upr if h else dn).append(abs(k))
    falls=[x[a] for a,b,h in segs if not h]
    period=(falls[-1]-falls[0])/(len(falls)-1)
    return {"top":float(np.mean(tops)),"bot":float(np.mean(bots)),
            "r_dn":float(np.mean(dn)),"r_up":float(np.mean(upr)),"period":float(period),
            "spread_top":float(np.ptp(tops)),"spread_bot":float(np.ptp(bots))}

def main():
    r29=float(sys.argv[1]) if len(sys.argv)>1 else 51e3
    dst=Path(sys.argv[2]) if len(sys.argv)>2 else DEFAULT_OUT
    x0,dx,n=CV_GRID
    rows=[]
    for k in range(n):
        cv=x0+dx*k
        r=characterize(cv,r29); rows.append(r)
        print(f"cv {cv:.3f}: period {r['period']*1e3:.4f} ms, top {r['top']:.4f}, "
              f"bot {r['bot']:.4f}, r_dn {r['r_dn']:.2f}, r_up {r['r_up']:.1f}",flush=True)
    out={"cv_grid":list(CV_GRID),"r29":r29,
         **{key:[r[key] for r in rows] for key in ("top","bot","r_dn","r_up","period")},
         "note":"D-5 sawtooth oscillator (IC2/IC4/TR2 parts of spice/d5_hiscore.cir, "
                f"TL081 and LM324 of opamps.lib, R29 {r29:g} ohm) against an ideal "
                f"control voltage, tran max step {TMAX}: effective turning points "
                "(intersections of line fits to the falling and rising segments), "
                "slopes and mean period. Generated by characterize_d5_vco.py."}
    dst.write_text(json.dumps(out,indent=0)+"\n")

if __name__=="__main__": main()
