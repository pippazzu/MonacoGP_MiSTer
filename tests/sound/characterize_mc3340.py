"""DC characterization of the MC3340 transistor-level model (spice/mc3340.lib).

Sweeps the input (pin 1) for a set of control voltages (pin 2) at a 12 V
supply, the output (pin 7) unloaded, and writes the output voltage and the
input current to build/sound/mc3340_dc.json (3 MB, not committed). The
sound model's MC3340 tables (mc3340_fit.py, data/mc3340_tables.json, which
is committed) are fitted to it. Needs ngspice.
Usage: characterize_mc3340.py [OUT.json]"""
import json
import sys
from pathlib import Path
import spice_run as S

HERE=Path(__file__).resolve().parent
DEFAULT_OUT=HERE.parents[1]/"build/sound/mc3340_dc.json"
VIN=(-2.0,7.0,0.01)
VC=[round(0.05*k,2) for k in range(0,161)]   # 0 .. 8 V

def main():
    base=""".title mc3340 dc
.include mc3340.lib
VCC vcc 0 12
VC ctl 0 DC {vc}
VIN in 0 DC 1.6
X1 in ctl 0 roll out vcc MC3340
"""
    out={"vin":None,"vc":VC,"out":[],"iin":[],
         "note":"MC3340 transistor model (spice/mc3340.lib), 12 V supply, output unloaded, "
                "ROLLOFF open. iin: current into pin 1 in A. Generated by characterize_mc3340.py."}
    for vc in VC:
        x,d=S.run(base.format(vc=vc),f"dc VIN {VIN[0]} {VIN[1]} {VIN[2]}",["v(out)","i(VIN)"])
        out["vin"]=[round(v,4) for v in x]
        out["out"].append([round(v,6) for v in d["v(out)"]])
        out["iin"].append([round(-i,10) for i in d["i(VIN)"]])
    dst=Path(sys.argv[1]) if len(sys.argv)>1 else DEFAULT_OUT
    dst.parent.mkdir(parents=True,exist_ok=True)
    dst.write_text(json.dumps(out,separators=(",",":")))

if __name__=="__main__": main()
